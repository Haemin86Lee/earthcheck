ROLE_LABELS = {
    ROLE_STUDENT: "학생",
    ROLE_TEACHER: "교사",
}

# ------------------------------------------------------------
# [생성형 AI(OpenAI ChatGPT) 연동 설정]
# 학생이 제출한 PDF 답안을 근거로 실제 AI가 객관식 재검사 문항을 생성할 때 사용합니다.
# 아래 환경변수를 실행 전에 설정해두어야 합니다 (터미널 예시):
#   Windows(PowerShell):  $env:OPENAI_API_KEY = "sk-..."
#   macOS/Linux:          export OPENAI_API_KEY="sk-..."
# 키가 없으면 문항 생성 화면에서 안내 메시지가 표시됩니다.
#
# Visual Studio Code에서 코드에 직접 키를 넣고 싶다면, 아래 OPENAI_API_KEY 줄의
# os.environ.get("OPENAI_API_KEY", "") 부분의 두 번째 인자("")에 키 문자열을 넣으면 됩니다.
# 예) OPENAI_API_KEY = os.environ.get("OPENAI_API_KEY", "sk-여기에-키-붙여넣기")
# (다만 키를 코드에 직접 적으면 실수로 깃허브 등에 올라갈 위험이 있으니, 개인 테스트용으로만
#  사용하고 다른 사람과 파일을 공유하기 전에는 꼭 지워주세요.)
# ------------------------------------------------------------
OPENAI_API_KEY = os.environ.get("OPENAI_API_KEY", "")
