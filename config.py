# config.py
# ------------------------------------------------------------
# 프로젝트 전역에서 공통으로 사용하는 "설정값(상수)"을 모아두는 파일입니다.
# 이렇게 한 곳에 모아두면, 나중에 폴더 경로나 정책(마감 시간, 문항 수 등)이
# 바뀌었을 때 이 파일 하나만 수정하면 되므로 유지보수가 편해집니다.
# ------------------------------------------------------------

import os  # 운영체제(OS)의 파일 경로를 다루기 위한 표준 라이브러리

# 현재 이 config.py 파일이 위치한 폴더의 절대경로를 구합니다.
# __file__ : 현재 실행 중인 파이썬 파일의 경로
# os.path.dirname() : 파일 경로에서 "폴더" 부분만 추출
BASE_DIR = os.path.dirname(os.path.abspath(__file__))

# ------------------------------------------------------------
# [DB 설정]
# SQLite는 "파일 하나"가 곧 데이터베이스입니다. 별도 서버 설치가 필요 없습니다.
# ------------------------------------------------------------
DB_PATH = os.path.join(BASE_DIR, "earthcheck.db")

# ------------------------------------------------------------
# [파일 업로드 설정]
# 학생이 제출하는 PDF 과제 파일을 저장할 로컬 폴더입니다.
# ------------------------------------------------------------
UPLOAD_DIR = os.path.join(BASE_DIR, "uploads")
os.makedirs(UPLOAD_DIR, exist_ok=True)  # 폴더가 없으면 자동으로 생성 (있으면 그냥 통과)
MAX_UPLOAD_MB = 10  # PDF 업로드 최대 용량 (MB) - 기획안 화면의 "PDF, 최대 10MB" 문구와 일치

# ------------------------------------------------------------
# [과제 확인 문항(재검사) 시험 설정]
# ------------------------------------------------------------
RETEST_QUESTION_COUNT = 10        # 재검사 문항 수 (기획안: 총 10문항)
