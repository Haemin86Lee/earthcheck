# ------------------------------------------------------------
# [역할(구분) 상수]
# 문자열을 코드 여기저기서 직접 타이핑하면 오타가 나기 쉬우므로 상수로 고정합니다.
# ------------------------------------------------------------
ROLE_STUDENT = "student"
